"""Production run of analyze_baseline_300_stats for BOTH splits.

For each split in (test-clean_300, test-other_300) this driver:
  - reads runs/<split>/metrics/audio_quality_results.csv
  - calls compute_per_method_summary, build_pairwise_table from
    analyze_baseline_300_stats
  - writes runs/<split>/metrics/per_method_summary.csv
  - writes runs/<split>/metrics/lca_vs_baselines_pairwise.csv
  - writes runs/<split>/reports/baseline_300_summary.md
    (uses analyze_baseline_300_stats.write_summary_md)

On per-split errors the full traceback is printed and the other split is
still attempted. A final JSON status line is printed at the end.
"""

from __future__ import annotations

import json
import sys
import traceback
from pathlib import Path

import pandas as pd

# Make sibling commands/ importable
_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))

import analyze_baseline_300_stats as abs300  # noqa: E402


SPLITS = ("test-clean_300", "test-other_300")


def _process_split(split: str) -> dict:
    runs_dir = abs300.EXPERIMENT_ROOT / "runs" / split
    csv_path = runs_dir / "metrics" / "audio_quality_results.csv"
    if not csv_path.exists():
        raise FileNotFoundError(f"missing input: {csv_path}")

    print(f"[{split}] Input CSV : {csv_path}")
    df = pd.read_csv(csv_path)
    required = {"method", "codec_setting", "sample_id"}
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"{csv_path} is missing required columns: {missing}")
    print(f"[{split}] Loaded rows: {len(df)}")

    summary = abs300.compute_per_method_summary(df)
    pairwise, notes = abs300.build_pairwise_table(df)

    metrics_dir = runs_dir / "metrics"
    reports_dir = runs_dir / "reports"
    metrics_dir.mkdir(parents=True, exist_ok=True)
    reports_dir.mkdir(parents=True, exist_ok=True)

    summary_csv = metrics_dir / "per_method_summary.csv"
    pairwise_csv = metrics_dir / "lca_vs_baselines_pairwise.csv"
    md_path = reports_dir / "baseline_300_summary.md"

    summary.to_csv(summary_csv, index=False)

    comment_line = (
        "# wilcoxon_implementation: "
        f"{'scipy.stats.wilcoxon' if abs300._HAVE_SCIPY else 'normal-approx fallback (z = T / sqrt(n*(n+1)*(2n+1)/6))'}"
        f"; bootstrap_resamples={abs300.BOOTSTRAP_RESAMPLES}; seed={abs300.BOOTSTRAP_SEED}; "
        "differences = LCA - baseline\n"
    )
    pairwise_csv_text = pairwise.to_csv(index=False)
    pairwise_csv.write_text(comment_line + pairwise_csv_text, encoding="utf-8")

    abs300.write_summary_md(split, summary, pairwise, notes, md_path)

    # Append a footer note referencing render_paper_section.
    try:
        with md_path.open("a", encoding="utf-8") as fh:
            fh.write(
                "\n---\n"
                "_Generated by `_run_analyze_production.py`. "
                "See sibling `render_paper_section.py` to render this into a "
                "paper-ready section._\n"
            )
    except Exception as exc:  # pragma: no cover
        print(f"[{split}] footer append failed: {exc!r}")

    print(f"[ok] {split}: wrote\n  {summary_csv}\n  {pairwise_csv}\n  {md_path}")
    return {
        "per_method_rows": int(len(summary)),
        "pairwise_rows": int(len(pairwise)),
        "summary_csv": str(summary_csv),
        "pairwise_csv": str(pairwise_csv),
        "report_md": str(md_path),
    }


def main() -> int:
    print(f"Experiment root : {abs300.EXPERIMENT_ROOT}")
    print(f"scipy available : {abs300._HAVE_SCIPY}")

    status: dict = {}
    any_error = False
    for split in SPLITS:
        print(f"\n=== {split} ===")
        try:
            res = _process_split(split)
            status[split] = {
                "per_method_rows": res["per_method_rows"],
                "pairwise_rows": res["pairwise_rows"],
                "summary_csv": res["summary_csv"],
                "pairwise_csv": res["pairwise_csv"],
                "report_md": res["report_md"],
            }
        except Exception:
            any_error = True
            print(f"[error] split={split} failed:")
            traceback.print_exc()
            status[split] = {"error": "see traceback above"}

    print("\n=== FINAL_JSON ===")
    print(json.dumps(status, ensure_ascii=False))
    return 1 if any_error else 0


if __name__ == "__main__":
    raise SystemExit(main())
